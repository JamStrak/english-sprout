"""Derive small hit outlines from existing plant alpha; never modify the art.

Run with Python + Pillow after replacing paper plant assets. The row envelopes
include every pixel with alpha >= 24, including leaves, without the blank sky.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'public/xiaoya/paper/v1'
files = [(name, ART / f'{name}.webp') for name in ('seed-in-soil', 'sprout', 'bud')]
files += [(f'flower-{p.stem}', p) for p in sorted((ART / 'flowers').glob('*.webp'))]
shapes = {}
for name, path in files:
    with Image.open(path) as image:
        assert image.size == (384, 512), (name, image.size)
        alpha = image.convert('RGBA').getchannel('A')
        left, right = [], []
        for y in range(0, 512, 12):
            band = alpha.crop((0, y, 384, min(512, y + 12))).point(lambda a: 255 if a >= 24 else 0)
            box = band.getbbox()
            if not box:
                continue
            x0, y0, x1, y1 = box
            left += [(x0, y + y0), (x0, y + y1)]
            right += [(x1, y + y0), (x1, y + y1)]
        points = left + right[::-1]
        shapes[name] = {'path': 'M' + 'L'.join(f'{x},{y}' for x, y in points) + 'Z',
                        'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
output = '// Generated by scripts/generate-meadow-hit-shapes.py from existing WebP alpha.\n'
output += '// Fixed hit geometry stays separate from animated artwork. Source canvas: 384 x 512.\n'
output += 'export const MEADOW_HIT_SHAPES = Object.freeze(' + json.dumps(shapes, ensure_ascii=False, separators=(',', ':')) + ');\n'
(ROOT / 'xiaoya/meadow-hit-shapes.js').write_text(output, encoding='utf-8')
print(f'Generated {len(shapes)} plant hit shapes ({len(output.encode())} bytes).')
