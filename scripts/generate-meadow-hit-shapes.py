"""Derive small hit outlines from existing plant alpha; never modify the art.

Run with Python + Pillow after replacing paper plant assets. The row envelopes
include every pixel with alpha >= 24, including leaves, without the blank sky.
"""
import hashlib
import json
import subprocess
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def discover_assets(root=ROOT):
    """Include released growth art only, retaining its full canvas and root."""
    art = Path(root) / 'public/xiaoya/paper'
    original = art / 'v1'
    files = {name: original / f'{name}.webp' for name in ('seed-in-soil', 'sprout', 'bud')}
    files.update((f'flower-{p.stem}', p) for p in sorted((original / 'flowers').glob('*.webp')))
    for flower in ('bow-rainbow', 'bow-starlight'):
        path = art / 'v2/flowers' / f'{flower}.webp'
        if path.is_file():
            files[f'flower-{flower}'] = path
    module = Path(root) / 'xiaoya/challenge-flowers.js'
    if module.is_file():
        script = "import {CHALLENGE_GROWTH_ASSETS} from './xiaoya/challenge-flowers.js'; console.log(JSON.stringify(CHALLENGE_GROWTH_ASSETS));"
        result = subprocess.run(['node', '--input-type=module', '-e', script], cwd=root,
                                check=True, capture_output=True, encoding='utf-8')
        files.update((key, Path(root) / 'public' / relative)
                     for key, relative in json.loads(result.stdout).items())
    return files


def build_shapes(files):
    shapes = {}
    for name, path in files.items():
        with Image.open(path) as image:
            if image.size != (384, 512):
                raise ValueError(f'{name}: expected 384 x 512, got {image.size}')
            alpha = image.convert('RGBA').getchannel('A')
            left, right = [], []
            for y in range(0, 512, 12):
                band = alpha.crop((0, y, 384, min(512, y + 12))).point(lambda a: 255 if a >= 24 else 0)
                box = band.getbbox()
                if not box:
                    continue
                x0, y0, x1, y1 = box
                left += [(x0, y + y0), (x0, y + y1)]
                right += [(x1, y + y0), (x1, y + y1)]
            points = left + right[::-1]
            if not points:
                raise ValueError(f'{name}: no visible alpha silhouette')
            bounds = alpha.point(lambda a: 255 if a >= 24 else 0).getbbox()
            shapes[name] = {'path': 'M' + 'L'.join(f'{x},{y}' for x, y in points) + 'Z',
                            'bounds': list(bounds),
                            'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
    return shapes


def main():
    shapes = build_shapes(discover_assets())
    output = '// Generated by scripts/generate-meadow-hit-shapes.py from existing WebP alpha.\n'
    output += '// Fixed hit geometry stays separate from animated artwork. Source canvas: 384 x 512.\n'
    output += 'export const MEADOW_HIT_SHAPES = Object.freeze(' + json.dumps(shapes, ensure_ascii=False, separators=(',', ':')) + ');\n'
    (ROOT / 'xiaoya/meadow-hit-shapes.js').write_text(output, encoding='utf-8')
    print(f'Generated {len(shapes)} plant hit shapes ({len(output.encode())} bytes).')


if __name__ == '__main__':
    main()
